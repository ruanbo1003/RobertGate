"""AI Videos 模块仓储接口（角色 / 设定图 / 项目 / 项目角色关联 / 分镜）。"""

from __future__ import annotations

from typing import Protocol

from app.domain.models.ai_video import (
    AvCharacter,
    AvCharacterImage,
    AvProject,
    AvProjectCharacter,
    AvShot,
)


class AvCharacterRepository(Protocol):
    async def find_by_id(self, id_: int) -> AvCharacter | None: ...

    async def find_by_name(self, name: str) -> AvCharacter | None: ...

    async def list_all(self) -> list[AvCharacter]: ...

    def add(self, entity: AvCharacter) -> None: ...

    async def delete(self, entity: AvCharacter) -> None: ...


class AvCharacterImageRepository(Protocol):
    async def find_by_id(self, id_: int) -> AvCharacterImage | None: ...

    async def list_by_character(self, character_id: int) -> list[AvCharacterImage]: ...

    def add(self, entity: AvCharacterImage) -> None: ...

    async def delete(self, entity: AvCharacterImage) -> None: ...


class AvProjectRepository(Protocol):
    async def find_by_id(self, id_: int) -> AvProject | None: ...

    async def list_page(self, page: int, page_size: int) -> tuple[list[AvProject], int]: ...

    def add(self, entity: AvProject) -> None: ...

    async def delete(self, entity: AvProject) -> None: ...


class AvProjectCharacterRepository(Protocol):
    async def list_by_project(self, project_id: int) -> list[AvProjectCharacter]: ...

    async def list_by_character(self, character_id: int) -> list[AvProjectCharacter]: ...

    async def used_counts(self) -> dict[int, int]:
        """character_id -> 被引用项目数。"""
        ...

    def add(self, entity: AvProjectCharacter) -> None: ...


class AvShotRepository(Protocol):
    async def find_by_id(self, id_: int) -> AvShot | None: ...

    async def list_by_project(self, project_id: int) -> list[AvShot]:
        """按 order_index 升序。"""
        ...

    async def delete_by_project(self, project_id: int) -> None: ...

    def add(self, entity: AvShot) -> None: ...

    async def delete(self, entity: AvShot) -> None: ...
