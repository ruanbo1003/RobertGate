"""invest-reports 仓储接口（Protocol）。实现见 infrastructure/repositories/invest_report_repo.py。"""

from __future__ import annotations

from typing import Protocol

from app.domain.models.invest_report import (
    IrChapter,
    IrChatMessage,
    IrProject,
    IrSample,
    IrSource,
    IrTemplate,
)


class IrSampleRepository(Protocol):
    async def find_by_id(self, id_: int) -> IrSample | None: ...
    def add(self, sample: IrSample) -> None: ...
    async def delete(self, sample: IrSample) -> None: ...
    async def list_by_type(self, type_: str) -> list[IrSample]: ...


class IrTemplateRepository(Protocol):
    async def find_by_type(self, type_: str) -> IrTemplate | None: ...
    def add(self, template: IrTemplate) -> None: ...


class IrProjectRepository(Protocol):
    async def find_by_id(self, id_: int) -> IrProject | None: ...
    def add(self, project: IrProject) -> None: ...
    async def delete(self, project: IrProject) -> None: ...
    async def list_page(self, page: int, page_size: int) -> tuple[list[IrProject], int]: ...


class IrChapterRepository(Protocol):
    async def find_by_id(self, id_: int) -> IrChapter | None: ...
    def add(self, chapter: IrChapter) -> None: ...
    async def list_by_project(self, project_id: int) -> list[IrChapter]: ...


class IrSourceRepository(Protocol):
    async def find_by_id(self, id_: int) -> IrSource | None: ...
    def add(self, source: IrSource) -> None: ...
    async def delete(self, source: IrSource) -> None: ...
    async def list_by_project(self, project_id: int) -> list[IrSource]: ...


class IrChatRepository(Protocol):
    def add(self, message: IrChatMessage) -> None: ...
    async def list_by_project(self, project_id: int, limit: int = 50) -> list[IrChatMessage]: ...
